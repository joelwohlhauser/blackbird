export type SlackEmojiGlyph =
  | { readonly kind: "unicode"; readonly value: string }
  | { readonly kind: "image"; readonly url: string }
  | { readonly kind: "text"; readonly value: string };

export function resolveSlackEmoji(
  name: string,
  custom: Readonly<Record<string, string>>,
): SlackEmojiGlyph {
  const base = name.split("::", 1)[0] ?? name;
  const customValue = custom[base];
  if (customValue !== undefined) {
    if (!customValue.startsWith("alias:")) return { kind: "image", url: customValue };
    const alias = customValue.slice("alias:".length);
    const aliased = custom[alias];
    if (aliased !== undefined && !aliased.startsWith("alias:")) {
      return { kind: "image", url: aliased };
    }
    const aliasedUnicode = SLACK_EMOJI[alias];
    if (aliasedUnicode !== undefined) return { kind: "unicode", value: aliasedUnicode };
  }
  const unicode = SLACK_EMOJI[base];
  return unicode === undefined
    ? { kind: "text", value: `:${name}:` }
    : { kind: "unicode", value: unicode };
}
